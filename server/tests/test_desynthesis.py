def test_duckduckgo_provider_parses_real_html_shape(monkeypatch):
    """HTTP stubbed; the DDG HTML parsing + uddg unwrap run for real."""
    from server.systems.agent import web_intelligence as wi

    html = """
    <div class="result">
      <a class="result__a" href="//duckduckgo.com/l/?uddg=https%3A%2F%2Fexample.com%2Fa">Example A</a>
      <a class="result__snippet">First snippet</a>
    </div>
    <div class="result">
      <a class="result__a" href="https://direct.com/b">Direct B</a>
      <a class="result__snippet">Second snippet</a>
    </div>
    """

    class Resp:
        text = html
        status_code = 200

        def raise_for_status(self):
            pass

    captured = {}

    def fake_post(url, **kw):
        captured["url"] = url
        return Resp()

    monkeypatch.setattr(wi.requests, "post", fake_post)
    results = wi.web_intel._search_duckduckgo("test query", 5)

    assert "duckduckgo.com/html" in captured["url"]
    assert results[0]["url"] == "https://example.com/a"   # uddg unwrapped
    assert results[1]["url"] == "https://direct.com/b"    # direct link kept
    assert results[0]["title"] == "Example A"


