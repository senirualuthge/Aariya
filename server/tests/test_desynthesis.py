def test_world_evaluation_comparisons_and_lookup():
    from server.systems.agent.multi_world import MultiWorldReasoning
    mw = MultiWorldReasoning()
    mw.worlds["actual"]["facts"] = {
        "door": "open", "alarm_armed": True, "temperature": 21.5}

    w = mw.evaluate_in_world
    assert w("actual", "door") == "open"
    assert w("actual", "Door") == "open"                    # case-insensitive
    assert w("actual", "door = closed") is False            # comparison
    assert w("actual", "alarm_armed = true") is True        # bool tolerance
    assert w("actual", "temperature = 21.5") is True        # numeric equality
    assert w("actual", "nonexistent_fact") is None          # honest absence
    assert w("missing_world", "door") is None


def test_counterfactual_branch_distance():
    from server.systems.agent.multi_world import multi_world
    name = multi_world.create_world(
        "no_power", modifications={"power": "off"})
    multi_world.worlds[name]["facts"]["power"] = "on"  # ensure divergence base
    d = multi_world.world_distance("actual", "no_power")
    assert d >= 1.0
