# ══════════════════════════ EMOTION PREDICTOR ════════════════════════════════

def test_ar1_fit_learns_from_observed_transitions():
    """Feed a window generated by a KNOWN linear process; the fitted model
    must recover its dynamics far better than a constant guess."""
    from server.systems.memory.emotion_predictor import EmotionPredictor

    p = EmotionPredictor(history_len=8)
    # True process: v_{t+1} = 0.9*v_t  (no intercept) — decaying toward 0.
    v = 0.8
    for _ in range(8):
        p.record(v, 0.5)
        v *= 0.9

    result = p.predict_next()
    assert result["method"] == "ar1-fit"
    fitted = p._fit_ar1(p._history)
    assert fitted is not None
    (_, phi_v), (_, phi_a) = fitted
    assert abs(phi_v - 0.9) < 0.05          # recovered the real coefficient
    # Forecast beats persistence by continuing the decay.
    expected = 0.9 * p._history[-1]["valence"]
    assert abs(result["predicted_valence"] - expected) < 0.02


def test_short_window_falls_back_to_heuristic_label():
    from server.systems.memory.emotion_predictor import EmotionPredictor
    p = EmotionPredictor()
    for v in (0.2, 0.4):
        p.record(v, 0.5)
    result = p.predict_next()
    assert result["method"] == "heuristic"   # too few transitions to fit
    assert -1.0 <= result["predicted_valence"] <= 1.0


